<h3 class="mt-[12px]">Mission and values</h3>
<p>
  Launched in December 2019, Shomrim (The Guardians) - The Center for Media and Democracy in Israel
  - is an independent, nonprofit newsroom dedicated to strengthening Israeli democracy through
  investigative journalism. Inspired by the ProPublica model, Shomrim operates free of commercial
  and political influence, providing fact-based, data-driven reporting that promotes public
  accountability. Its investigations are published in partnership with leading media outlets across
  print, broadcast and digital platforms to maximize reach and impact.
</p>
<p>
  Shomrim invests the time and resources required for rigorous investigative work and continues to
  follow stories beyond publication. Its mission is to lead investigations with social impact,
  amplify underrepresented voices and examine issues affecting communities that are often
  overlooked.
</p>
