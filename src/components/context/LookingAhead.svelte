  <h2>Looking ahead</h2>
  <p>
    Looking ahead to 2026, Shomrim will continue to pursue its core mission: demanding
    accountability and transparency from decision-makers and giving voice to those excluded from the
    tables of power. The coming year is expected to be dramatic in Israel, with national elections
    taking place in the aftermath of the war and amid ongoing efforts to undermine democratic values
    and institutions. In this complex and fragile environment, Shomrim will remain a trusted beacon
    of independent investigative journalism, producing rigorous, public-interest reporting. At the
    same time, we will invest in developing new and critical tools, including advanced use of
    freedom-of-information mechanisms and AI-supported investigative methods to strengthen our
    ability to serve the public and uphold democratic oversight.
