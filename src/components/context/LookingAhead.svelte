<h2 id="looking-ahead">Looking Ahead</h2>
<p>
  Shomrim’s model rests on three interconnected pillars: investigative journalism at scale, training
  and ecosystem-building for investigative journalism in Israel, and the integration of AI and
  innovation in the newsroom. Together, these pillars form a cohesive framework that combines
  rigorous reporting, professional development, and technological advancement.
</p>
<h3>Training</h3>
<p>
  Israel lacks a sustainable training pathway for the next generation of investigative journalists,
  particularly from communities underrepresented in mainstream media. Shomrim addresses this gap
  through mentorship, on-the-job training, and diverse programs for students and early-career
  journalists, building skills while expanding the field’s talent base.
</p>
<h3>AI Lab</h3>
<p>
  Complementing this work, Shomrim’s AI Impact Lab serves as a hub for experimentation and
  implementation of AI tools in journalism. The Lab develops and co-creates tailored technologies,
  embedding innovation into both newsroom practice and training. Each pillar reinforces the others —
  training feeds new talent into the newsroom, innovation enhances reporting and education, and
  real-world investigations shape both curricula and tools.
</p>
<p>
  Looking ahead to 2026, Shomrim will continue to pursue its core mission: demanding accountability
  and transparency from decision-makers and giving voice to those excluded from the tables of power.
  The coming year is expected to be dramatic in Israel, with national elections taking place in the
  aftermath of the war and amid ongoing efforts to undermine democratic values and institutions. In
  this complex and fragile environment, Shomrim will remain a trusted beacon of independent
  investigative journalism, producing rigorous, public-interest reporting. At the same time, we will
  invest in developing new and critical tools, including advanced use of freedom-of-information
  mechanisms and AI-supported investigative methods to strengthen our ability to serve the public
  and uphold democratic oversight.
</p>
