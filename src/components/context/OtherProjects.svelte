  <h2>Other Projects: AI and Training</h2>
  <p>
    Shomrim’s model rests on three interconnected pillars: investigative journalism at scale,
    training and ecosystem-building for investigative journalism in Israel, and the integration of
    AI and innovation in the newsroom. Together, these pillars form a cohesive framework that
    combines rigorous reporting, professional development, and technological advancement.
  </p>
  <div class="flex gap-6.25 my-3.25">
    <div class="font-semibold w-15.75">Training</div>
    <div class="max-w-225">
      Israel lacks a sustainable training pathway for the next generation of investigative
      journalists, particularly from communities underrepresented in mainstream media. Shomrim
      addresses this gap through mentorship, on-the-job training, and diverse programs for students
      and early-career journalists, building skills while expanding the field’s talent base.
    </div>
  </div>
  <div class="flex gap-6.25 my-3.25">
    <div class="font-semibold w-15.75 shrink-0">AI Lab</div>
    <div class="max-w-225">
      Complementing this work, Shomrim’s AI Impact Lab serves as a hub for experimentation and
      implementation of AI tools in journalism. The Lab develops and co-creates tailored
      technologies, embedding innovation into both newsroom practice and training. Each pillar
      reinforces the others—training feeds new talent into the newsroom, innovation enhances
      reporting and education, and real-world investigations shape both curricula and tools.
    </div>
  </div>
