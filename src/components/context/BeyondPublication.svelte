  <h2>Beyond publication</h2>
  <p>
    Shomrim’s work does not end at publication; in many cases, publication marks only the midpoint
    of the investigative process. With the goal of driving meaningful, real-world change, Shomrim
    actively follows each investigation beyond the initial report, working to ensure that findings
    reach centers of power - decision-makers, regulators and influential actors in civil society -
    who are positioned to advance reform, correction, and accountability.
  </p>
  <p>
    To support this work, Shomrim has developed a distinct impact model within the Israeli media
    landscape. This model systematically tracks the consequences of our reporting after publication,
    identifies opportunities for follow-up, and sustains pressure where needed - recognizing that
    accountability is often achieved not through a single story, but through continued engagement
    over time.
  </p>
</section>
