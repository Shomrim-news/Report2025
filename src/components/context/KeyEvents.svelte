<h2 id="key-events" class="as-h1">Key Events in 2025</h2>
<h3>International Journalism Festival in Perugia</h3>
<p>
  In April, Shomrim journalist Milan Czerny participated in the International Journalism Festival in
  Perugia, Italy. Czerny took part in a panel titled “Censorship and Self-Censorship in Media During
  Wars,” which examined the challenges journalists face in times of conflict. The discussion focused
  on how, during wartime, media outlets are often subject to increased censorship by authorities, as
  well as self-censorship driven by concerns about national interests or public backlash. The panel
  explored the experiences of journalists from Israel and Ukraine who have encountered varying
  degrees of both external and internal censorship during war.
</p>
<h3>Social media enhancement</h3>
<p>
  2025 was a significant year for Shomrim’s efforts to enhance social media reach among
  underrepresented communities. Shomrim established a series of collaborations with social media
  platforms and pages serving diverse audiences, including young people, the Arab public, and
  Russian-speaking communities in Israel. Shomrim’s investigations, as well as adapted summaries,
  were translated into relevant languages and achieved unprecedented reach and engagement among
  these audiences.
</p>
<h3>AI in the Newsroom - developing a unique tool to identify biases and missing information</h3>
<p>
  In 2025, Shomrim also continued its work on developing AI tools for the newsroom. In addition to a
  grant received from the London School of Economics (LSE) and the Google News Initiative, the David
  David Foundation joined in supporting the development of an AI tool designed to assess the
  reliability of sources and journalistic writing. The tool aims to identify biases and logical gaps
  that journalists may overlook, thereby strengthening the credibility of journalistic texts and
  increasing reliance on verified facts and established information rather than inference or
  cognitive shortcuts.
</p>
